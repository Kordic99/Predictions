'use strict';
// Package existing LOCAL files only. No network, timestamps or changes to sources.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const files={archive:'data/predictions/2026-27.json',rosters:'rosters-live.json',
  schedule:'schedule-live.json',context:'match-context-live.json',evidence:'prediction-evidence-live.json'};
function build(){
  const data={schemaVersion:1,hashes:{}};
  for(const [key,name]of Object.entries(files)){
    // Git may check text out as CRLF on Windows; normalize only line endings.
    const raw=fs.readFileSync(path.join(root,name),'utf8').replace(/\r\n/g,'\n');
    data.hashes[name]=crypto.createHash('sha256').update(raw).digest('hex');
    data[key]=JSON.parse(raw);
  }
  return '// Generated by scripts/build_offline_snapshot.cjs from preserved local JSON files.\n'
    +'window.OFFLINE_SAVED_DATA = '+JSON.stringify(data).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029')+';\n';
}
if(require.main===module){
  const output=path.join(root,'offline-saved-data.js'),content=build();
  if(process.argv.includes('--check')){
    if(fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n')!==content)throw new Error('Offline snapshot differs from the preserved JSON sources');
    console.log('Offline snapshot matches every source file.');
  }else{fs.writeFileSync(output,content);console.log('Packaged saved data without network access.');}
}
module.exports={build,files};
